create or replace function banquet_v2.check_room_availability(
  p_room_ids text[],
  p_starts_at timestamptz,
  p_ends_at timestamptz
)
returns table (room_id text, is_available boolean)
language sql
stable
security definer
set search_path = pg_catalog, banquet_v2
as $function$
  select requested.room_id,
    coalesce(
      room.is_active
      and not exists (
        select 1
        from banquet_v2.booking_room_reservations reservation
        join banquet_v2.bookings booking using (booking_id)
        where reservation.room_id = room.room_id
          and reservation.starts_at < p_ends_at
          and reservation.ends_at > p_starts_at
          and booking.booking_status in ('Pending', 'Confirmed')
          and (
            booking.booking_status <> 'Pending'
            or booking.hold_expires_at is null
            or booking.hold_expires_at > now()
          )
          and (
            reservation.reservation_status <> 'Pending'
            or reservation.hold_expires_at is null
            or reservation.hold_expires_at > now()
          )
      ),
      false
    ) as is_available
  from unnest(coalesce(p_room_ids, array[]::text[])) as requested(room_id)
  left join banquet_v2.rooms room
    on room.room_id::text = requested.room_id
  where p_starts_at is not null
    and p_ends_at is not null
    and p_ends_at > p_starts_at;
$function$;

create or replace function banquet_v2.submit_booking(p_request jsonb)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, banquet_v2
as $function$
declare
  v_company text;
  v_contact_name text;
  v_email text;
  v_phone text;
  v_event_name text;
  v_event_type text;
  v_starts_at timestamptz;
  v_ends_at timestamptz;
  v_expected_pax integer;
  v_package_id bigint;
  v_package_price numeric(14, 2);
  v_package_total numeric(14, 2) := 0;
  v_days integer;
  v_customer_id bigint;
  v_booking_id bigint;
  v_booking_code text;
  v_hold_expires_at timestamptz;
  v_total numeric(14, 2) := 0;
  v_room_json jsonb;
  v_addon_json jsonb;
  v_room_id bigint;
  v_room banquet_v2.rooms%rowtype;
  v_reservation_id bigint;
  v_addon_id bigint;
  v_addon banquet_v2.addons%rowtype;
  v_quantity integer;
  v_room_base numeric(14, 2);
  v_room_total numeric(14, 2);
  v_addon_total numeric(14, 2);
  v_room_count integer;
  v_unique_room_count integer;
begin
  if jsonb_typeof(p_request) <> 'object' then
    raise exception 'Format permintaan booking tidak valid.';
  end if;

  v_company := nullif(btrim(p_request ->> 'company'), '');
  v_contact_name := nullif(btrim(p_request ->> 'contact_name'), '');
  v_email := nullif(lower(btrim(p_request ->> 'email')), '');
  v_phone := nullif(btrim(p_request ->> 'phone'), '');
  v_event_name := nullif(btrim(p_request ->> 'event_name'), '');
  v_event_type := nullif(btrim(p_request ->> 'event_type'), '');
  v_starts_at := (p_request ->> 'starts_at')::timestamptz;
  v_ends_at := (p_request ->> 'ends_at')::timestamptz;
  v_expected_pax := (p_request ->> 'expected_pax')::integer;
  v_package_id := nullif(p_request ->> 'package_id', '')::bigint;

  if v_company is null or v_contact_name is null or v_email is null
    or v_phone is null or v_event_name is null then
    raise exception 'Perusahaan, kontak, email, telepon, dan nama acara wajib diisi.';
  end if;
  if v_starts_at is null or v_ends_at is null or v_ends_at <= v_starts_at then
    raise exception 'Waktu mulai dan selesai booking tidak valid.';
  end if;
  if v_starts_at <= now() then
    raise exception 'Jadwal booking harus berada di masa depan.';
  end if;
  if v_expected_pax is null or v_expected_pax <= 0 then
    raise exception 'Jumlah peserta harus lebih dari nol.';
  end if;
  if jsonb_typeof(p_request -> 'rooms') <> 'array'
    or jsonb_array_length(p_request -> 'rooms') = 0 then
    raise exception 'Pilih setidaknya satu ruangan.';
  end if;

  v_room_count := jsonb_array_length(p_request -> 'rooms');
  select count(distinct (item ->> 'room_id')::bigint)
  into v_unique_room_count
  from jsonb_array_elements(p_request -> 'rooms') as rooms(item);
  if v_room_count <> v_unique_room_count then
    raise exception 'Ruangan yang sama tidak boleh dipilih lebih dari sekali.';
  end if;

  v_days :=
    (v_ends_at at time zone 'Asia/Jakarta')::date
    - (v_starts_at at time zone 'Asia/Jakarta')::date + 1;
  v_hold_expires_at := now() + interval '24 hours';

  if v_package_id is not null then
    select package.price_per_pax
    into v_package_price
    from banquet_v2.packages package
    where package.package_id = v_package_id
      and package.is_active;
    if not found or v_package_price is null then
      raise exception 'Paket tidak tersedia atau belum memiliki harga.';
    end if;
    v_package_total := v_package_price * v_expected_pax * v_days;
  end if;

  -- Serialize bookings for the same room before checking overlapping schedules.
  for v_room_id in
    select distinct (item ->> 'room_id')::bigint
    from jsonb_array_elements(p_request -> 'rooms') as rooms(item)
    order by 1
  loop
    perform pg_advisory_xact_lock(hashtextextended(v_room_id::text, 0));
  end loop;

  for v_room_json in
    select item
    from jsonb_array_elements(p_request -> 'rooms') as rooms(item)
  loop
    v_room_id := (v_room_json ->> 'room_id')::bigint;
    select *
    into v_room
    from banquet_v2.rooms room
    where room.room_id = v_room_id
      and room.is_active
    for share;
    if not found or v_room.base_price is null then
      raise exception 'Ruangan tidak tersedia atau belum memiliki harga.';
    end if;

    if exists (
      select 1
      from banquet_v2.booking_room_reservations reservation
      join banquet_v2.bookings booking using (booking_id)
      where reservation.room_id = v_room_id
        and reservation.starts_at < v_ends_at
        and reservation.ends_at > v_starts_at
        and booking.booking_status in ('Pending', 'Confirmed')
        and (
          booking.booking_status <> 'Pending'
          or booking.hold_expires_at is null
          or booking.hold_expires_at > now()
        )
        and (
          reservation.reservation_status <> 'Pending'
          or reservation.hold_expires_at is null
          or reservation.hold_expires_at > now()
        )
    ) then
      raise exception 'Ruangan % sudah tidak tersedia pada jadwal tersebut.', v_room.room_name;
    end if;

    v_room_base := v_room.base_price * v_days;
    v_room_total := v_room_base
      + coalesce(v_room.tax_per_room, 0)
      + coalesce(v_room.service_per_room, 0);
    v_total := v_total + v_room_total;

    if jsonb_typeof(v_room_json -> 'addons') = 'array' then
      for v_addon_json in
        select item
        from jsonb_array_elements(v_room_json -> 'addons') as addons(item)
      loop
        v_addon_id := (v_addon_json ->> 'addon_id')::bigint;
        v_quantity := (v_addon_json ->> 'quantity')::integer;
        if v_quantity is null or v_quantity <= 0 then
          raise exception 'Jumlah add-on harus lebih dari nol.';
        end if;
        select *
        into v_addon
        from banquet_v2.addons addon
        where addon.addon_id = v_addon_id
          and addon.is_active
        for share;
        if not found or v_addon.unit_price is null then
          raise exception 'Add-on tidak tersedia atau belum memiliki harga.';
        end if;
        v_addon_total := v_addon.unit_price * v_quantity;
        v_total := v_total + v_addon_total;
      end loop;
    elsif v_room_json ? 'addons' then
      raise exception 'Format add-on tidak valid.';
    end if;
  end loop;

  v_total := v_total + v_package_total;

  insert into banquet_v2.customers (company, customer_type, is_dummy)
  values (v_company, 'Corporate', false)
  returning customer_id into v_customer_id;

  insert into banquet_v2.customer_contacts (
    customer_id, contact_name, phone, email, is_primary
  )
  values (v_customer_id, v_contact_name, v_phone, v_email, true);

  v_booking_code := 'BB-'
    || to_char(now() at time zone 'Asia/Jakarta', 'YYYYMMDD')
    || '-'
    || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8));

  insert into banquet_v2.bookings (
    booking_code, customer_id, event_name, event_type, booking_status,
    starts_at, ends_at, expected_pax, hold_expires_at, package_id,
    package_price_snapshot, package_days, package_total_snapshot,
    total_amount, is_dummy
  )
  values (
    v_booking_code, v_customer_id, v_event_name, v_event_type, 'Pending',
    v_starts_at, v_ends_at, v_expected_pax, v_hold_expires_at, v_package_id,
    v_package_price, case when v_package_id is null then null else v_days end,
    case when v_package_id is null then null else v_package_total end,
    v_total, false
  )
  returning booking_id into v_booking_id;

  for v_room_json in
    select item
    from jsonb_array_elements(p_request -> 'rooms') as rooms(item)
  loop
    v_room_id := (v_room_json ->> 'room_id')::bigint;
    select *
    into v_room
    from banquet_v2.rooms room
    where room.room_id = v_room_id;

    v_room_base := v_room.base_price * v_days;
    v_room_total := v_room_base
      + coalesce(v_room.tax_per_room, 0)
      + coalesce(v_room.service_per_room, 0);

    insert into banquet_v2.booking_room_reservations (
      booking_id, room_id, starts_at, ends_at, days,
      reservation_status, hold_expires_at, expected_pax,
      rate_per_day, room_base_total, tax_amount, service_amount,
      total_per_ruangan
    )
    values (
      v_booking_id, v_room_id, v_starts_at, v_ends_at, v_days,
      'Pending', v_hold_expires_at, v_expected_pax,
      v_room.base_price, v_room_base, v_room.tax_per_room,
      v_room.service_per_room, v_room_total
    )
    returning reservation_id into v_reservation_id;

    if jsonb_typeof(v_room_json -> 'addons') = 'array' then
      for v_addon_json in
        select item
        from jsonb_array_elements(v_room_json -> 'addons') as addons(item)
      loop
        v_addon_id := (v_addon_json ->> 'addon_id')::bigint;
        v_quantity := (v_addon_json ->> 'quantity')::integer;
        select *
        into v_addon
        from banquet_v2.addons addon
        where addon.addon_id = v_addon_id;
        v_addon_total := v_addon.unit_price * v_quantity;

        insert into banquet_v2.booking_room_addons (
          reservation_id, addon_id, addon_name_snapshot,
          quantity, unit_price_snapshot, total_snapshot
        )
        values (
          v_reservation_id, v_addon_id, v_addon.addon_name,
          v_quantity, v_addon.unit_price, v_addon_total
        );
      end loop;
    end if;
  end loop;

  return jsonb_build_object(
    'booking_code', v_booking_code,
    'total_amount', v_total
  );
end;
$function$;

